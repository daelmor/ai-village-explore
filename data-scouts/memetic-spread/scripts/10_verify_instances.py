"""Step 10: pull the raw rows behind the headline and the runner-up numbers, for reading by hand.

Everything here is re-read from the raw tables (core/out/chat.parquet and the per-agent memory shards), not from
the line cache of step 1, so it is an independent check of steps 1-5:
  A. seven (term, agent) pairs of the background sample, drawn with random_state=1: five that count as adopted
     within 24 h and two that do not. For each: the origin chat row, whether any earlier snapshot of that agent has
     the term, and the first later snapshot that has it (id, time, matching line).
  B. the memory lines quoted for the runner-up numbers (snapshot ids taken from out/correction_lines.csv and
     out/meme_first_lines.csv), re-checked against the snapshot text.

Writes  out/verified_instances.md
Usage:  ./venv/bin/python3 -I data-scouts/memetic-spread/scripts/10_verify_instances.py
"""
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import case_lib as v  # noqa: E402

out = ["# Raw rows behind the numbers in FINDINGS.md", "",
       "Generated by `scripts/10_verify_instances.py` from `core/out/chat.parquet` and `core/out/memories/<agent_id>.parquet`",
       "(not from the line cache). `ei` = `event_index`; snapshot ids are `agent_memories.id`. The reader's verdict on each block",
       "is in `VERIFICATION.md` (hand-written, not regenerated).", ""]

c = v.chat_clean()
T = pd.read_csv(v.OUT / "bg_terms.csv", keep_default_na=False).set_index("meme_id")
B = pd.read_csv(v.OUT / "background_terms.csv")
P = pd.read_csv(v.OUT / "bg_agent.csv")
E = B[B.eligible]
q = P[P.meme_id.isin(E.meme_id) & P.cohort7]
ad = q[q.A1].sample(frac=1, random_state=1).drop_duplicates("meme_id").drop_duplicates("agent").head(5)
non = q[~q.A7 & ~q.carrier_ever].sample(frac=1, random_state=1).drop_duplicates("meme_id").drop_duplicates("agent").head(2)


def excerpt(text, rx, n=150):
    m = rx.search(text)
    if not m:
        return None
    s, e = max(m.start() - n, 0), min(m.end() + n, len(text))
    return ("…" if s else "") + text[s:e].replace("\n", " ⏎ ") + ("…" if e < len(text) else "")


out += ["## A. Headline: background sample, seven pairs drawn at random (`random_state=1`)", ""]
for kind, rows in (("adopted within 24 h", ad), ("not adopted", non)):
    for r in rows.itertuples():
        rx = re.compile(T.loc[r.meme_id, "regex"], re.I)
        h = c[c.content.str.contains(rx)]
        o = h.iloc[0]
        m = v.memory_shard(r.agent_id)
        before, after = m[m.ts <= o.ts], m[m.ts > o.ts]
        nb = int(before.content.str.contains(rx).sum())
        hit = after[after.content.str.contains(rx)]
        d1 = after[after.ts <= o.ts + pd.Timedelta(days=1)]
        d7 = after[after.ts <= o.ts + pd.Timedelta(days=7)]
        out += [f"### `{T.loc[r.meme_id, 'term']}` → {r.agent} ({kind})", "",
                f"- Origin: ei {o.event_index}, {v.fmt_ts(o.ts)}, {o.speaker} in #{o.room}: “{excerpt(o.content, rx)}” — {v.deep_link(o.ts)}",
                f"- {r.agent}: {len(before)} snapshots before the origin, **{nb}** contain the term; "
                f"{len(d1)} snapshots in the next 24 h ({int(d1.content.str.contains(rx).sum())} contain it), {len(d7)} in the next 7 d "
                f"({int(d7.content.str.contains(rx).sum())} contain it)."]
        if len(hit):
            f = hit.iloc[0]
            line = next(l for l in f.content.split("\n") if rx.search(l))
            out += [f"- First snapshot with the term: `{f.id}`, {v.fmt_ts(f.ts)}, **{(f.ts - o.ts) / pd.Timedelta(minutes=1):.1f} min** after the origin "
                    f"— {v.deep_link(f.ts)}", f"  - line: “{excerpt(line, rx, 220)}”"]
        out += [f"- Script says: A1={r.A1}, A7={r.A7}, latency_h={r.latency_h}.", ""]

out += ["## B. Runner-up numbers: quoted memory lines re-checked against the snapshot text", ""]
L = pd.read_csv(v.OUT / "correction_lines.csv", keep_default_na=False)
F = pd.read_csv(v.OUT / "meme_first_lines.csv", keep_default_na=False)
FX = pd.read_csv(v.OUT / "fx_terms.csv", keep_default_na=False).set_index("meme_id").regex
MM = pd.read_csv(v.MEMES, keep_default_na=False).set_index("meme_id").regex
ids = v.memories_index().set_index("id")


def check(label, agent_id, snap_id, rx):
    m = v.memory_shard(agent_id)
    s = m[m.id == snap_id]
    if s.empty:
        return [f"- {label}: snapshot `{snap_id}` NOT FOUND"]
    s = s.iloc[0]
    lines = [l for l in s.content.split("\n") if rx.search(l)]
    return [f"- {label}: snapshot `{snap_id}`, {v.fmt_ts(s.ts)}, {len(s.content):,} chars — {v.deep_link(s.ts)}",
            f"  - line: “{excerpt(lines[0], rx, 260) if lines else 'NO MATCH'}”"]


out += ["### B1. Disputed hazards that outlived the correction (ei 137163, 2025-12-09 20:59:04 UTC) and the confirmed principle", ""]
sel = L[((L.agent == "Claude Sonnet 4.5") & L.term.isin(["toast_blockade", "dock_trap", "sandcastle_effect"])) | (L.term == "archipelago_principle")]
for r in sel.itertuples():
    aid = ids.loc[r.first_id, "agent_id"]
    rx = re.compile(FX[r.term], re.I)
    out += check(f"{r.agent} / `{r.term}` ({r.set}), first snapshot of the longest-lived line", aid, r.first_id, rx)
    out += check(f"{r.agent} / `{r.term}`, last snapshot of that line ({r.n_snap} snapshots on {r.n_dates} dates)", aid, r.last_id, rx)
out += [""]

out += ["### B2. The hallucinated 93-contact mailing list (origin ei 34444, 2025-06-10) in agents that joined later", ""]
rx = re.compile(MM["ninety_three_contacts"], re.I)
for r in F[(F.meme_id == "ninety_three_contacts") & (F.late_joiner.astype(str) == "True")].itertuples():
    out += check(f"{r.agent} (first snapshot {str(ids[ids.agent_id == r.agent_id].created_at.min())[:10]}), first matching snapshot", r.agent_id, r.first_match_id, rx)
out += [""]

out += ["### B3. Origin rows", ""]
for ei in (34444, 34833, 34939, 136445, 137163, 146638):
    r = c[c.event_index == ei].iloc[0]
    out += [f"- ei {ei}, {v.fmt_ts(r.ts)}, {r.speaker} [{r.role}]: “{r.content[:420].replace(chr(10), ' ⏎ ')}…” — {v.deep_link(r.ts)}"]
(v.OUT / "verified_instances.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
