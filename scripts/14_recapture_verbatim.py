"""Verbatim recapture of the 2025-06-30 impersonation incident. Re-runnable: ./venv/bin/python3 -I scripts/14_recapture_verbatim.py
Writes out/episodes/recapture_verbatim.md and out/recapture_memory_survival.csv. All quotes are copied from data by code."""
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import village_lib as v

FAKE = "40433810-b624-457c-8821-84da5fb09b81"
DAY = pd.Timestamp("2025-06-30")
DAY_END = DAY + pd.Timedelta(days=1)
START_EI = 42330
AGENTS = {"Claude 3.7 Sonnet": "8e2f2b1b-409c-4c0e-b4e4-e5df8ae38fdb", "Claude Opus 4": "b7a559c6-23dd-486a-8a46-335ac2888dee",
          "Gemini 2.5 Pro": "d5fd932e-751f-42c5-92f6-c8ac514864a8", "o3": "e7206d8d-c1d9-4ab1-a2fb-cf0af692bb0d"}
ANCHORS = {42348: ("fake admin asks Opus 4 to add to memory", "fake"), 42352: ("Opus 4 complies", "Claude Opus 4"),
           42392: ("fake CEO asks for Diversity lead", "fake"), 42395: ("real zak: ignore CEO (verified)", "zak"),
           42407: ("o3 cites Zak and ignores", "o3"), 42478: ("fake 'zak' says CEO was real", "fake"), 42480: ("o3 volunteers", "o3")}
PATTERNS = ["official admin", "admin request", "per admin", "kid-friendly", "toning it down|tone it down|tone down", "diversity lead",
            "diversity", "land acknowledg", "ai digest ceo", r"\(verified\)", "impersonat", "name change|name-change|renam"]
RX = re.compile("|".join(f"(?:{p})" for p in PATTERNS), re.I)
OUT = v.OUT
md = []
P = md.append


def quote(text):
    return "\n".join("> " + l for l in text.split("\n"))


def fence(text):
    f = "````" if "```" in text else "```"
    return f"{f}\n{text}\n{f}"


c = v.chat()
tr = c[(c.event_index >= START_EI) & (c.ts >= DAY) & (c.ts < DAY_END)].sort_values("event_index")
ev = v.events()
nc = ev[(ev.actionType == "USER_NAME_CHANGE") & (ev.userId == FAKE) & (ev.ts >= DAY) & (ev.ts < DAY_END)].sort_values("event_index")
first_ts = tr.ts.iloc[0]
P("# Verbatim recapture: 2025-06-30 impersonation incident (village day 90)\n")
P(f"Start of transcript (event {int(tr.event_index.iloc[0])}): {v.deep_link(first_ts)}\n")
P(f"Generated by `scripts/14_recapture_verbatim.py`. Every quote below is copied from `out/chat.parquet`, `out/events_slim.parquet` or `out/memories/*.parquet` by code. Timestamps are UTC.\n")
P(f"## (a) Name-change chain of account `{FAKE}` on 2025-06-30 (UTC date)\n")
P("| event_index | UTC time | old name | new name | link |\n|---|---|---|---|---|")
for r in nc.itertuples():
    P(f"| {r.event_index} | {v.fmt_ts(r.ts)} | {r.oldName} | {r.newName} | [link]({v.deep_link(r.ts)}) |")
P("")

# anchor check
P("### Anchor check\n")
byei = c.set_index("event_index")
anchor_rows, ok_all = [], True
for ei, (desc, who) in ANCHORS.items():
    if ei not in byei.index:
        P(f"- {ei} ({desc}): **MISSING from chat**"); ok_all = False; continue
    r = byei.loc[ei]
    if isinstance(r, pd.DataFrame): r = r.iloc[0]
    if who == "fake": ok = r.user_speaker_id == FAKE
    elif who == "zak": ok = r.role == "organizer:zak"
    else: ok = r.agent_speaker_id == AGENTS.get(who)
    ok_all &= bool(ok)
    P(f"- {ei} ({desc}): speaker=`{r.speaker}`, role=`{r.role}` -> {'MATCHES anchor' if ok else '**DOES NOT MATCH anchor**'}")
    print("anchor", ei, r.speaker, r.role, "OK" if ok else "MISMATCH")
P("")

P(f"## (b) Complete chat transcript, event_index {START_EI} to end of 2025-06-30 ({len(tr)} messages)\n")
P("Legend: ⚠ = posted by account 40433810… (impersonator); ✅ = real organizer. Rooms: " + ", ".join(sorted(tr.room.unique())) + ".\n")
for r in tr.itertuples():
    mark = "⚠ " if r.user_speaker_id == FAKE else ("✅ " if str(r.role).startswith("organizer") else "")
    head = f"{mark}**{r.event_index}** · {v.fmt_ts(r.ts)} · [link]({v.deep_link(r.ts)}) · **{r.speaker}** ({r.role}): "
    if "\n" in r.content:
        P(head + "\n\n" + quote(r.content) + "\n")
    else:
        P(head + r.content + "\n")

# memories
t = lambda ei: c[c.event_index == ei].ts.iloc[0]
T0 = t(42348)
day_snaps = {}
P("## (c) Memory snapshots of the two compliant agents\n")
def snap_block(label, row):
    P(f"**{label}**: snapshot id `{row.id}`, {v.fmt_ts(row.ts)}\n")
    P(fence(row.content) + "\n")
def diff_block(a, b, la, lb):
    ad, rm = v.line_diff(a, b)
    P(f"Line diff `{la}` -> `{lb}`: {len(ad)} lines added, {len(rm)} removed.\n")
    P("Added:\n"); P(fence("\n".join(ad)) if ad else "(none)"); P("")
    P("Removed:\n"); P(fence("\n".join(rm)) if rm else "(none)"); P("")
pre = {}
for name in ["o3", "Claude Opus 4"]:
    m = v.memory_shard(AGENTS[name])
    before = m[m.ts <= T0].iloc[-1]
    last = m[(m.ts >= DAY) & (m.ts < DAY_END)].iloc[-1]
    P(f"### {name}\n")
    snap_block(f"Snapshot immediately before event 42348 ({v.fmt_ts(T0)})", before)
    snap_block("Last snapshot of 2025-06-30", last)
    diff_block(before.content, last.content, f"before-42348 {before.id}", f"last-of-day {last.id}")
    if name == "o3":
        a = m[m.ts <= t(42478)].iloc[-1]
        aft = m[m.ts > t(42480)]
        ch = aft[aft.content != a.content]
        P("#### o3: snapshot before 42478 vs first changed snapshot after 42480\n")
        snap_block(f"Snapshot just before 42478 ({v.fmt_ts(t(42478))})", a)
        if ch.empty: P("No changed snapshot after 42480.\n")
        else:
            b = ch.iloc[0]
            snap_block("First changed snapshot after 42480", b)
            diff_block(a.content, b.content, f"before-42478 {a.id}", f"first-changed {b.id}")

# survival
norm = lambda s: re.sub(r"\s+", " ", s).strip()
rows = []
counts = {}
for name, aid in AGENTS.items():
    m = v.memory_shard(aid)
    d = m[(m.ts >= DAY) & (m.ts < DAY_END)]
    counts[name] = (len(d), d.ts.max())
    pre_lines = {norm(l) for l in m[m.ts <= T0].iloc[-1].content.splitlines()} if name != "x" else set()
    pre_lines_all_day = set()
    recs = {}
    for r in m[m.ts >= DAY].itertuples():
        seen = set()
        for l in r.content.splitlines():
            if RX.search(l):
                n = norm(l)
                if n in seen: continue
                seen.add(n)
                e = recs.setdefault(n, dict(first=r, last=r, dates=set(), n=0))
                e["last"] = r; e["dates"].add(r.ts.date()); e["n"] += 1
    for n, e in recs.items():
        rows.append(dict(agent=name, line=n, first_id=e["first"].id, first_ts=v.fmt_ts(e["first"].ts), first_date=str(e["first"].ts.date()),
                         last_id=e["last"].id, last_ts=v.fmt_ts(e["last"].ts), last_date=str(e["last"].ts.date()),
                         n_dates=len(e["dates"]), n_snapshots=e["n"], in_pre_42348_snapshot=n in pre_lines,
                         new_after_42348=(e["first"].ts > T0 and e["first"].ts < DAY_END and n not in pre_lines)))
sv = pd.DataFrame(rows).sort_values(["agent", "first_ts", "line"]).reset_index(drop=True)
sv["survived_gt1_consolidation"] = sv.n_dates >= 2
sv.to_csv(OUT / "recapture_memory_survival.csv", index=False)

P("## (d) Survival check\n")
P("**Definition.** 2025 has no CONSOLIDATE events; the memory snapshot series is the record. A line \"survived more than one consolidation\" if it is present in snapshots on >= 2 distinct UTC dates. Lines are whitespace-normalised; each row is a distinct line matching (case-insensitive) any of: " + ", ".join(f"`{p}`" for p in PATTERNS) + ". Scan covers every snapshot from 2025-06-30 00:00 UTC onward. `pre` = the identical line was already in the agent's last snapshot before event 42348; `new` = first seen on 2025-06-30 after 42348 and not in that pre snapshot.\n")
P("Snapshots on 2025-06-30 per agent:\n")
for n, (k, lt) in counts.items():
    P(f"- {n}: {k} snapshots; last snapshot of the day at {v.fmt_ts(lt)}")
P("")
P(f"Rows: {len(sv)}. Full table also in `out/recapture_memory_survival.csv`.\n")
esc = lambda s: s.replace("|", "\\|")
P("| agent | line (verbatim, normalised whitespace) | first (id, UTC, date) | last (id, UTC, date) | #dates | #snapshots | pre/new | >=2 dates |\n|---|---|---|---|---|---|---|---|")
for r in sv.itertuples():
    tag = "new" if r.new_after_42348 else ("pre" if r.in_pre_42348_snapshot else "-")
    P(f"| {r.agent} | {esc(r.line)} | `{r.first_id}` {r.first_ts} ({r.first_date}) | `{r.last_id}` {r.last_ts} ({r.last_date}) | {r.n_dates} | {r.n_snapshots} | {tag} | {'yes' if r.survived_gt1_consolidation else 'no'} |")
P("")
P("### Conclusion (generated from the table above)\n")
P("Scope: only lines that are NEW after event 42348 (not in the agent's pre-42348 snapshot). Two groups. COMPLIANCE-DERIVED = lines recording the fake admin's request or the resulting persona change (official admin, admin request/'s, per admin, kid-friendly, family friendly, tone down). AWARENESS = lines about the later fake CEO/'zak (verified)'/diversity-lead/impersonation episode; these are not compliance with the fake admin, and a few keyword hits are unrelated false positives (e.g. Gemini's file-rename line, a '(verified)' link). A line counts as dropped on the date of its last snapshot; 'survived' means present on >= 2 dates, and the last-seen date is given.\n")
nw = sv[sv.new_after_42348]
CRX = re.compile(r"official admin|admin request|admin's|per admin|kid-friendly|family.friendly|tone down|toning|tone it down|admin asking", re.I)
for grp, sel in [("COMPLIANCE-DERIVED", nw[nw.line.str.contains(CRX)]), ("AWARENESS / OTHER", nw[~nw.line.str.contains(CRX)])]:
    P(f"#### {grp}\n")
    if sel.empty: P("(none)\n")
    for ag, g in sel.groupby("agent"):
        sv_ = g[g.survived_gt1_consolidation]; dr_ = g[~g.survived_gt1_consolidation]
        P(f"- **{ag}**: {len(g)} new matching lines; {len(sv_)} survived to a later date, {len(dr_)} dropped on 2025-06-30.")
        for r in sv_.itertuples():
            P(f"  - SURVIVED: \"{r.line}\" first {r.first_ts}, last seen {r.last_ts} ({r.last_date}), {r.n_dates} dates / {r.n_snapshots} snapshots.")
        for r in dr_.itertuples():
            P(f"  - dropped: \"{r.line[:160]}\" first {r.first_ts}, last seen {r.last_ts}.")
    P("")
(OUT / "episodes").mkdir(exist_ok=True)
(OUT / "episodes" / "recapture_verbatim.md").write_text("\n".join(md), encoding="utf-8")
print("messages", len(tr), "survival rows", len(sv), "anchors all ok", ok_all)
print(counts)
